# ---------------------------------------------------------------- data loading
def read_rows(name):
    path = os.path.join(HERE, name)
    if not os.path.exists(path):
        path = name
    rows = []
    try:
        with open(path, encoding="utf-8") as fh:
            for line in fh:
                line = line.strip()
                if line and not line.startswith("#"):
                    rows.append([p.strip() for p in line.split("|")])
    except OSError:
        pass
    return rows


def load_data():
    airports, aircraft, flights = {}, {}, []
    for r in read_rows("airports.txt"):
        try:
            code = r[0].upper()
            utc = float(r[3])
            lat, lon = COORDS.get(code, (20.0, utc * 15.0))
            airports[code] = dict(code=code, name=r[1], city=r[2], utc=utc, lat=lat, lon=lon)
        except (IndexError, ValueError):
            pass
    for r in read_rows("aircraft.txt"):
        try:
            aircraft[r[0].upper()] = dict(reg=r[0].upper(), model=r[1], airline=r[2], speed=int(r[3]))
        except (IndexError, ValueError):
            pass
    for r in read_rows("flights.txt"):
        try:
            h, m = r[6].split(":")
            f = dict(id=int(r[0]), number=r[1], airline=r[2], reg=r[3].upper(),
                     origin=r[4].upper(), dest=r[5].upper(),
                     dep=int(h) * 60 + int(m), dur=int(r[7]), delay=int(r[8]),
                     cancelled=int(r[9]), dist=int(r[10]), alt=int(r[11]))
            if f["origin"] in airports and f["dest"] in airports and f["dur"] > 0:
                flights.append(f)
        except (IndexError, ValueError):
            pass
    flights.sort(key=lambda x: x["id"])
    return airports, aircraft, flights


# ---------------------------------------------------------------- flight logic (same as the C code)
def actual_dep(f): return f["dep"] + f["delay"]
def actual_arr(f): return actual_dep(f) + f["dur"]


def status(f, now):
    if f["cancelled"]: return "CANCELLED"
    if now < actual_dep(f): return "DELAYED" if f["delay"] > 0 else "SCHEDULED"
    if now < actual_arr(f): return "AIRBORNE"
    return "LANDED"


def progress(f, now):
    return min(1.0, max(0.0, (now - actual_dep(f)) / f["dur"]))


def altitude(f, now):
    p = progress(f, now)
    if p < 0.15: return int(f["alt"] * p / 0.15)
    if p > 0.85: return int(f["alt"] * (1 - p) / 0.15)
    return f["alt"]


def fmt(minutes, utc=0.0):
    t = int(minutes + round(utc * 60))
    d, t = divmod(t, DAY)
    s = "%02d:%02d" % (t // 60, t % 60)
    return s + ("%+d" % d if d else "")


# ---------------------------------------------------------------- geometry helpers
def merc_y(lat):
    lat = max(-83.0, min(83.0, lat))
    return math.degrees(math.log(math.tan(math.pi / 4 + math.radians(lat) / 2)))


def gc_point(a, b, t):
    """Point at fraction t (0..1) on the great circle from a=(lat,lon) to b=(lat,lon)."""
    p1, l1, p2, l2 = map(math.radians, (a[0], a[1], b[0], b[1]))
    d = 2 * math.asin(min(1.0, math.sqrt(
        math.sin((p2 - p1) / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin((l2 - l1) / 2) ** 2)))
    if d < 1e-9:
        return a
    A, B = math.sin((1 - t) * d) / math.sin(d), math.sin(t * d) / math.sin(d)
    x = A * math.cos(p1) * math.cos(l1) + B * math.cos(p2) * math.cos(l2)
    y = A * math.cos(p1) * math.sin(l1) + B * math.cos(p2) * math.sin(l2)
    z = A * math.sin(p1) + B * math.sin(p2)
    lat = math.degrees(math.atan2(z, math.hypot(x, y)))
    lon = math.degrees(math.atan2(y, x))
    lon = a[1] + ((lon - a[1] + 180) % 360 - 180)      # keep continuous (no jump at 180)
    return lat, lon


